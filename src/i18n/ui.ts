const dictionaries: Record<Locale, Record<UiKey, string>> = { en, es };

/** Returns a translator for the locale; `{name}` placeholders are filled from `vars`. */
export function useTranslations(locale: Locale) {
  return (key: UiKey, vars: Record<string, string> = {}): string =>
    dictionaries[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => vars[name] ?? `{${name}}`);
}
